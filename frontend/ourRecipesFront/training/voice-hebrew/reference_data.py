def normalize(text):return re.sub(r'[\W_]+','',text).lower()


def training(heldout_rows):
    forbidden={normalize(r['utterance']) for r in heldout_rows};result=[];seen={}
    def add(label,text):
        key=normalize(text)
        if key in forbidden:return
        if key in seen:
            if seen[key]!=label:raise ValueError('Conflicting text-only semantic labels')
            return
        seen[key]=label;result.append({'text':text,'label':label})
    for label,forms in TRAIN.items():
        for text in forms:
            for prefix in ('','עדכון מהמטבח: '):add(label,prefix+text)
    for text in HARD_OTHER:
        for prefix in ('','עדכון מהמטבח: '):add('other',prefix+text)
    recs,rows=load_data()
    for row in [r for r in rows if r['split']=='train'][::3]:add('other',row['utterance'])
    return result
